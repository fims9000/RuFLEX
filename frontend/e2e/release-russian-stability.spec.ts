import { expect, test } from "@playwright/test";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { mkdirSync } from "node:fs";
import { openTrainingSettings } from "./helpers/trainingSettings";

test("Russian stability route freezes native evidence and reopens without duplicate writes", async ({ page }, testInfo) => {
  test.skip(process.env.VITE_RUFLEX_UI_LANG !== "ru", "Russian release acceptance");
  test.setTimeout(90_000);
  const path = join(tmpdir(), `ruflex-release-stability-${Date.now()}`);
  await page.setViewportSize({ width: 1100, height: 800 });
  await page.goto("/");
  await expect(page.locator(".inspector")).toBeHidden();
  await page.getByLabel("Папка проекта").fill(path);
  await page.getByLabel("Название проекта").fill("Устойчивость учебной модели");
  await page.getByLabel("Тип нового проекта").selectOption("practice");
  await page.getByRole("button", { name: "Создать проект", exact: true }).click();
  await openTrainingSettings(page);
  await page.getByLabel("Модель для обучения").selectOption("decision_tree");
  await page.getByLabel("Seed эксперимента").fill("11,13,17");
  await page.getByLabel("Что меняется между запусками").selectOption("TRAINING_VARIABILITY");
  await page.locator('[data-ruflex-action="study.start"]').click();
  await expect(page.getByRole("heading", { name: "Насколько согласованы решения моделей" })).toBeVisible({ timeout: 30_000 });
  const historyRuns = page.locator("details.object-tree-children");
  await expect(historyRuns).not.toHaveAttribute("open", "");
  await historyRuns.locator("summary").click();
  await expect(historyRuns.locator("button")).toHaveCount(3);
  await expect(historyRuns).toContainText("Завершено");
  await historyRuns.locator("summary").click();
  await page.getByRole("button", { name: "Сравнить решения моделей", exact: true }).click();
  await expect(page.getByText("Уверенность и поддержка решения другими моделями", { exact: true })).toBeVisible({ timeout: 30_000 });
  const save = page.getByRole("button", { name: "Зафиксировать правило проверки", exact: true });
  await save.click();
  await expect(page.getByRole("button", { name: "Правило сохранено", exact: true })).toBeDisabled();
  await expect(page.getByText("Ошибки среди принятых прогнозов на валидации", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Пример для сравнения решений")).toBeVisible();
  await page.getByText("Прогнозы всех обучений", { exact: true }).click();
  const fits = page.getByText("Прогнозы всех обучений", { exact: true }).locator("..");
  await expect(fits.locator("tbody tr")).toHaveCount(3);
  const capture = async (name: string) => {
    const folder = process.env.RUFLEX_CAPTURE_RELEASE === "1" ? resolve("..", "docs", "qa", "screenshots", "release-candidate") : testInfo.outputDir;
    mkdirSync(folder, { recursive: true });
    await page.getByText("Уверенность и поддержка решения другими моделями", { exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: join(folder, name), animations: "disabled" });
  };
  await capture("stability-light.png");
  await page.getByLabel("Сменить тему").click();
  await expect(page.locator("html")).toHaveAttribute("data-ruflex-theme", "dark");
  await expect(page.getByRole("button", { name: "Правило сохранено", exact: true })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1);
  await capture("stability-dark.png");
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await page.getByLabel("Папка проекта").fill(path);
  await page.getByRole("button", { name: "Открыть проект", exact: true }).click();
  await page.getByRole("navigation", { name: "Разделы Studio" }).getByRole("button", { name: "Обучение", exact: true }).click();
  await expect(page.getByRole("button", { name: "Правило сохранено", exact: true })).toBeDisabled();
  await expect(page.getByRole("alert")).toHaveCount(0);
});
