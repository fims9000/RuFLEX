import { expect, test } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

test("practice template persists data and reaches model, explanation and explicit final test", async ({ page }) => {
  test.skip(process.env.VITE_RUFLEX_UI_LANG !== "ru", "Run with VITE_RUFLEX_UI_LANG=ru");
  test.setTimeout(120_000);
  const path = join(tmpdir(), `ruflex-practice-project-${Date.now()}-${Math.random().toString(16).slice(2)}`);
  const screenshots = resolve("..", "docs", "qa", "screenshots");
  const capture = async (name: string) => {
    if (process.env.RUFLEX_CAPTURE_DEMO_SCREENSHOTS !== "1") return;
    mkdirSync(screenshots, { recursive: true });
    await page.screenshot({ path: join(screenshots, name), fullPage: true, animations: "disabled" });
  };
  await page.setViewportSize({ width: 1280, height: 850 });
  await page.goto("/");
  await page.getByLabel("Папка проекта").fill(path);
  await page.getByLabel("Название проекта").fill("Учебный проект RuFLEX");
  await page.getByLabel("Тип нового проекта").selectOption("practice");
  await capture("practice-01-create.png");
  const createdResponse = page.waitForResponse((response) => response.url().endsWith("/api/projects") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Создать проект" }).click();
  const created = await (await createdResponse).json() as { session_id: string };
  const selector = page.getByLabel("Модель для обучения");
  await expect(selector).toBeEnabled();
  const datasetResponse = await page.request.get(`http://127.0.0.1:8010/api/projects/${created.session_id}/dataset`);
  expect(datasetResponse.status()).toBe(200);
  const dataset = await datasetResponse.json() as { profile: { row_count: number }; contract: { target: string; task: string; id_columns: string[] } };
  expect(dataset.profile.row_count).toBe(80);
  expect(dataset.contract).toMatchObject({ target: "target", task: "binary_classification", id_columns: ["entity_id"] });
  await expect(selector.locator("option")).toHaveCount(6);
  await selector.selectOption("decision_tree");
  await capture("practice-02-model-choice.png");
  const fitResponse = page.waitForResponse((response) => response.url().endsWith("/api/projects/training/run") && response.request().method() === "POST");
  await page.locator('[data-ruflex-action="training.run"]').click();
  expect((await fitResponse).status()).toBe(201);
  await page.getByRole("navigation", { name: "Разделы Studio" }).getByRole("button", { name: "Анализ" }).click();
  await page.locator('[data-ruflex-action="evaluation.save"]').click();
  await expect(page.getByRole("heading", { name: "Прогнозы на валидации" })).toBeVisible();
  await page.locator('[data-ruflex-action="threshold.select"]').click();
  await expect(page.getByRole("button", { name: /Порог решения.*raw/ })).toBeVisible();
  await page.getByRole("navigation", { name: "Разделы Studio" }).getByRole("button", { name: "Доказательства" }).click();
  const method = page.getByLabel("Метод объяснения");
  await expect(method.locator('option[value="occlusion"]')).toHaveCount(1);
  await expect(method.locator('option[value="shap"]')).toHaveCount(1);
  await expect(method.locator('option[value="tree_shap"]')).toHaveCount(1);
  await method.selectOption("occlusion");
  await page.locator('[data-ruflex-action="explanation.generate"]').click();
  await expect(page.getByTestId("explanation-job")).toContainText("SUCCEEDED");
  await page.locator('[data-ruflex-action="explanation.check"]').click();
  await expect(page.getByText("PASSED_AVAILABLE_CHECKS", { exact: true })).toBeVisible();
  await capture("practice-03-explanation.png");
  await page.getByRole("navigation", { name: "Разделы Studio" }).getByRole("button", { name: "Анализ" }).click();
  await expect(page.getByRole("heading", { name: "Финальный тест закрыт" })).toBeVisible();
  await page.locator(".final-test-confirm input").check();
  const finalResponse = page.waitForResponse((response) => response.url().endsWith("/api/projects/analyses/final-test") && response.request().method() === "POST");
  await page.locator('[data-ruflex-action="final_test.execute"]').click();
  expect((await finalResponse).status()).toBe(201);
  await expect(page.getByRole("heading", { name: "Результат финального теста сохранён отдельно" })).toBeVisible();
  await capture("practice-04-final-test.png");
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await page.getByLabel("Папка проекта").fill(path);
  await page.getByRole("button", { name: "Открыть проект", exact: true }).click();
  await page.getByRole("navigation", { name: "Разделы Studio" }).getByRole("button", { name: "Анализ" }).click();
  await expect(page.getByRole("heading", { name: "Результат финального теста сохранён отдельно" })).toBeVisible();
});
