def build_template_based_russian_manuscript() -> Path:
    build_article_schemes()
    profile = load_article_profile()
    regression_rows = _read_csv_rows(TABLES_DIR / "regression_results_table.csv")
    classification_rows = _read_csv_rows(TABLES_DIR / "classification_results_table.csv")

    with tempfile.TemporaryDirectory(prefix="ruflex_template_doc_") as temp_dir:
        temp_root = Path(temp_dir)
        _convert_template_to_docx(temp_root)
        template_docx = temp_root / "shablon-dokladov.docx"
        document = Document(template_docx)
        _clear_document_body(document)
        _populate_document(document, profile, regression_rows, classification_rows)
        OUTPUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
        document.save(OUTPUT_DOCX)
    return OUTPUT_DOCX


