def _add_table_caption(document: Document, text: str) -> None:
    _add_paragraph(document, text, style="Заголовок табл", align="center")


def _add_metric_table(document: Document, *, headers: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> None:
    table = document.add_table(rows=1, cols=len(headers))
    try:
        table.style = "Table Grid"
    except KeyError:
        pass
    for index, header in enumerate(headers):
        table.rows[0].cells[index].text = header
    for row in rows:
        cells = table.add_row().cells
        for index, value in enumerate(row):
            cells[index].text = value
    document.add_paragraph()


def _add_picture_with_caption(document: Document, image_path: Path, caption: str, *, width: float) -> None:
    document.add_picture(str(image_path), width=Inches(width))
    _add_paragraph(document, caption, style="Нумерация рисунка", align="center")


def _add_paragraph(document: Document, text: str, *, style: str, align: str | None = None) -> None:
    paragraph = document.add_paragraph()
    try:
        paragraph.style = style
    except KeyError:
        pass
    if align == "center":
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.add_run(text)


def _fmt(value: str) -> str:
    return f"{float(value):.6f}"


def _ru_variant_label(label: str) -> str:
    mapping = {
        "Flat Baseline": "Плоская базовая конфигурация",
        "Flat Interpretable": "Плоская интерпретируемая конфигурация",
        "Deep Article Demo": "Демонстрационный глубокий режим",
        "Deep Research": "Расширенный глубокий режим",
    }
    return mapping.get(label, label)


